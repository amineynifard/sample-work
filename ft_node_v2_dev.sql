-- WHOLE GRAPH IN ONE RUN
--   * AT START      : ROOT'S TOP 3 + ROOT'S OTHER                       (TRN_LEVEL = 1, PARENT_NODE_ID IS NULL)
--   * CLICK OTHER   : ROOT'S RANKS 4..6 + A FINAL OTHER FOR RANKS 7+    (TRN_LEVEL = 2, PARENT_NODE_ID = ROOT'S OTHER)
--                     INDIVIDUALS AMONG RANKS 4..6 CAN BE EXPANDED TOO; THE FINAL OTHER CANNOT
--   * CLICK PERSON  : THAT PERSON'S TOP 3 + OTHER, ROOT EXCLUDED        (TRN_LEVEL = 2, PARENT_NODE_ID = THAT PERSON)
--                     ONLY THE ROOT'S RANKS 1..6 WITH IS_REAL = 1 ARE EXPANDED (LEGAL CUSTOMERS, IS_REAL = 0, ARE NOT)
--   * CLICK HOP-2   : TOP 3 + OTHER OF A HOP-2 PERSON (IS_REAL = 1)     (TRN_LEVEL = 3, PARENT_NODE_ID = THAT PERSON)
--                     ROOT AND HOP-2 PEOPLE EXCLUDED; HOP-3 PEOPLE ARE NOT EXPANDED
--   * OTHER NODE IDS: ROOT'S OTHER = -(ROOT*10+1), ROOT'S FINAL OTHER = -(ROOT*10+2), PERSON'S OTHER = -(PERSON*10+1)
--   * A NODE IS CLICKABLE WHEN IT IS THE PARENT_NODE_ID OF SOME EDGE (NODE FUNCTION: IS_EXPANDABLE = 1)
--   * OUTSIDE OUR BANK: EACH ACCOUNT IS ITS OWN NODE, ID = 9000000000000 + ORA_HASH(ACCOUNT NUMBER, OR NAME IF NO ACCOUNT),
--                     NAME FROM THE TRANSACTION, IS_REAL IS NULL, NEVER EXPANDED (CUSTOMER 0 IS NO LONGER USED)
--------------------------------------------------------------------------
-- FNT_AML_GRAPH_EDGE_V2 AND FNT_AML_GRAPH_NODE_V2 ARE INDEPENDENT (EACH HAS ITS OWN QUERY); COMPILE IN ANY ORDER.
--------------------------------------------------------------------------
CREATE OR REPLACE TYPE T_TF_AML_GRAPH_NODE_V2_ROW FORCE AS OBJECT (
      TRANSACTION_DATE       NUMBER
    , NODE_ID                NUMBER
    , IS_REAL                NUMBER(1)
    , REAL_OR_LEGAL          CHAR(10 CHAR)
    , FIRST_NAME             VARCHAR2(255 CHAR)
    , LAST_NAME              VARCHAR2(255 CHAR)
    , CUSTOMER_NAME          VARCHAR2(255 CHAR)
    , NATIONAL_CODE          VARCHAR2(255 CHAR)
    , IS_EXPANDABLE          NUMBER(1)
    , BRANCH_CODE            VARCHAR2(50 CHAR)
    , BRANCH_NAME            VARCHAR2(1000 CHAR)
    , LOCATION_STATUS        VARCHAR2(50 CHAR)
  );
/
CREATE OR REPLACE TYPE T_TF_AML_GRAPH_NODE_V2_TBL AS TABLE OF T_TF_AML_GRAPH_NODE_V2_ROW;
/
create or replace FUNCTION             FNT_AML_GRAPH_NODE_V2 (
                                                                    P_START_DATE  NUMBER DEFAULT NULL
                                                                    , P_END_DATE  NUMBER DEFAULT NULL
                                                                    , P_CUSTOMER_NUMBER  NUMBER DEFAULT NULL
                                                                )
RETURN T_TF_AML_GRAPH_NODE_V2_TBL IS
  SQL_TEXT     CLOB;
  OUT_RECORD   T_TF_AML_GRAPH_NODE_V2_TBL;
  V_START_date varchar2(1000);
  V_END_date varchar2(1000);
  V_CUSTOMER_NUMBER varchar2(1000);
L_LOG_ID  NUMBER;
LL_LOG_ID NUMBER;
L_PARAMS  VARCHAR2(4000);
L_COUNT   NUMBER :=0;
L_ERROR   VARCHAR2(4000);
l_ERROR_CORE  VARCHAR2(400);
BEGIN
--------------------------------------------------------------------------
--DB
-- L_PARAMS:= 'P_START_DATE='||P_START_DATE||',P_END_DATE='||P_END_DATE||',P_CUSTOMER_NUMBER='||P_CUSTOMER_NUMBER;
--  DW_LOG.sp_logger(P_FUNCTION_NAME =>'FNT_AML_GRAPH_NODE_V2' ,
--                  P_PARAMS        => L_PARAMS,
--                  P_LOG_ID_OUT    => L_LOG_ID,
--                  P_TYPE          => 1);
----------------------------------------------------------------------------
--TEST CASE
--SELECT * from TABLE (FNT_AML_GRAPH_NODE_V2(14050214, 14050214, 24356845));
IF P_START_DATE IS NULL OR P_END_DATE IS NULL OR P_CUSTOMER_NUMBER IS NULL OR P_START_DATE > P_END_DATE THEN
   OUT_RECORD := T_TF_AML_GRAPH_NODE_V2_TBL();          /* NOTHING TO SEARCH : RETURN EMPTY WITHOUT PARSING / RUNNING THE HEAVY QUERY */
ELSE
V_START_date := 'BILL.TRANSACTION_DATE >= ' || P_START_DATE ;
V_END_date := 'and BILL.TRANSACTION_DATE <= ' || P_END_DATE ;
V_CUSTOMER_NUMBER := 'CUSTOMER_NUMBER = ' || P_CUSTOMER_NUMBER;
  SQL_TEXT := '
    SELECT
    T_TF_AML_GRAPH_NODE_V2_ROW(
                    TRANSACTION_DATE
                    , NODE_ID
                    , IS_REAL
                    , REAL_OR_LEGAL
                    , FIRST_NAME
                    , LAST_NAME
                    , CUSTOMER_NAME
                    , NATIONAL_CODE
                    , IS_EXPANDABLE
                    , BRANCH_CODE
                    , BRANCH_NAME
                    , LOCATION_STATUS
                  )
    FROM
      (
		WITH ROOT_CUSTOMER AS
		(
			SELECT
				CUSTOMER_ID
				, CUSTOMER_NUMBER
				, DEPOSIT_NUMBER
			FROM
				UDL.DPST_DEPOSIT_CUSTOMER
			WHERE
				' || V_CUSTOMER_NUMBER || '
		)
		, BILL_TRX AS
		(
			SELECT
				BILL.DEPOSIT_NUMBER
				, BILL.DI_DEBTOR
				, BILL.DI_AMOUNT
				, R.CUSTOMER_ID
				, R.CUSTOMER_NUMBER
				, BILL.TRANSACTION_DATE
				, BILL.TRX_ABOUT_CODE
				, BILL.TRX_ABOUT_NAME
				, BILL.CUSTOMER_ID_OPPOSITE AS PEER_CUSTOMER_ID     /* COUNTERPARTY''S CUSTOMER ID, NULL OUTSIDE OUR BANK */
				, CASE WHEN DI_DEBTOR = 1 THEN BILL.DEST_DEPOSIT_NUMBER WHEN DI_DEBTOR = 0 THEN SRC_DEPOSIT_NUMBER END AS TRX_DEPOSIT_NUMBER
				, BILL.TRX_FIRST_NAME ||''''|| BILL.TRX_LAST_NAME AS TRX_NAME
			FROM
				UDL.AML_BILL_TRANSACTION_ARCH BILL INNER JOIN ROOT_CUSTOMER R ON R.DEPOSIT_NUMBER = BILL.DEPOSIT_NUMBER
			WHERE
				1=1
				AND ' || V_START_DATE || '  ' || V_END_DATE || '
				AND BILL.TRANSACTION_TYPE_CODE <> 1010
		)
		, BASE_TRX AS
		(
			SELECT /*+MATERIALIZE*/
				CUSTOMER_ID
				, CUSTOMER_NUMBER
				, DEPOSIT_NUMBER
				, TRX_DEPOSIT_NUMBER
				, DI_DEBTOR
				, PEER_CUSTOMER_ID
				, MAX(TRANSACTION_DATE) AS TRANSACTION_DATE
				, MIN(TRX_ABOUT_CODE) AS TRX_ABOUT_CODE
				, MIN(TRX_ABOUT_NAME) AS TRX_ABOUT_NAME
				, CASE WHEN DI_DEBTOR = 1 THEN DEPOSIT_NUMBER ELSE TRX_DEPOSIT_NUMBER END AS SRC_DEPOSIT_NUMBER
				, CASE WHEN DI_DEBTOR = 0 THEN DEPOSIT_NUMBER ELSE TRX_DEPOSIT_NUMBER END AS DEST_DEPOSIT_NUMBER
				, TRX_NAME
				, SUM(DI_AMOUNT) AS TOTAL_AMOUNT
				, COUNT(*) AS CNT
				, MAX(DI_AMOUNT) AS MAX_AMOUNT
			FROM
				BILL_TRX
			GROUP BY
				CUSTOMER_ID
				, CUSTOMER_NUMBER
				, DEPOSIT_NUMBER
				, TRX_DEPOSIT_NUMBER
				, DI_DEBTOR
				, TRX_NAME     /* KEEPS OUTSIDE-BANK PEOPLE WITHOUT AN ACCOUNT NUMBER APART */
				, PEER_CUSTOMER_ID
		)
		, TRX AS
		(
			SELECT
				T1.TRANSACTION_DATE
				, T1.CUSTOMER_ID
				, T1.CUSTOMER_NUMBER
				, T1.DI_DEBTOR
				, NVL(T1.SRC_DEPOSIT_NUMBER ,0) AS SRC_DEPOSIT_NUMBER
				, NVL(T1.DEST_DEPOSIT_NUMBER ,0) AS DEST_DEPOSIT_NUMBER
				, T1.PEER_CUSTOMER_ID
				, NVL(T1.PEER_CUSTOMER_ID, 9000000000000 + ORA_HASH(NVL(T1.TRX_DEPOSIT_NUMBER, NVL(T1.TRX_NAME, ''UNKNOWN'')))) AS PEER_KEY     /* OUR CUSTOMER : CUSTOMER ID; OUTSIDE OUR BANK : ONE KEY PER ACCOUNT */
				, T1.TRX_NAME AS PEER_NAME
				, T1.TRX_ABOUT_CODE
				, T1.TRX_ABOUT_NAME
				, T1.TOTAL_AMOUNT
				, T1.CNT
				, T1.MAX_AMOUNT
				, SUM(T1.TOTAL_AMOUNT) OVER (PARTITION BY T1.CUSTOMER_ID, NVL(T1.PEER_CUSTOMER_ID, 9000000000000 + ORA_HASH(NVL(T1.TRX_DEPOSIT_NUMBER, NVL(T1.TRX_NAME, ''UNKNOWN''))))) AS PEER_TOTAL
			FROM
				BASE_TRX T1
		)
		, PEER_RANK AS
		(
			SELECT /*+MATERIALIZE*/
				T.*
				, DENSE_RANK() OVER (PARTITION BY T.CUSTOMER_ID ORDER BY T.PEER_TOTAL DESC, T.PEER_KEY) AS RN
				, 1 AS HOP
			FROM
				TRX T
		)
		/* ===== HOP 2 : THE ROOT''S RANKS 1..6 (TOP 3 + THE OTHER''S 2ND TOP 3) WHO ARE INDIVIDUALS (IS_REAL = 1) ARE EXPANDED ===== */
		, EXPAND_CUSTOMER AS
		(
			SELECT /*+ USE_NL(C) */
				C.ID AS PEER_CUSTOMER_ID
				, C.CUSTOMER_NUMBER AS PEER_NUMBER
			FROM
				(
					SELECT /*+ NO_MERGE */ DISTINCT
						P.PEER_CUSTOMER_ID
					FROM
						PEER_RANK P
					WHERE
						P.RN <= 6     /* EVERY PERSON THE ROOT''S GRAPH CAN SHOW : TOP 3 AND RANKS 4..6 */
						AND P.PEER_CUSTOMER_ID <> P.CUSTOMER_ID
				) P INNER JOIN UDL.CSTM_CUSTOMER@drep C ON P.PEER_CUSTOMER_ID = C.ID     /* AT MOST 6 LOOKUPS */
			WHERE
				C.IS_REAL = 1
		)
		, EXPAND_DEPOSIT AS
		(
			SELECT /*+ LEADING(E) USE_NL(D) */
				D.CUSTOMER_ID
				, D.CUSTOMER_NUMBER
				, D.DEPOSIT_NUMBER
			FROM
				EXPAND_CUSTOMER E INNER JOIN UDL.DPST_DEPOSIT_CUSTOMER D ON D.CUSTOMER_NUMBER = E.PEER_NUMBER
		)
		, BILL_TRX2 AS
		(
			SELECT /*+ LEADING(R) USE_NL(BILL) */     /* ONE KEYED LOOKUP PER DEPOSIT (ALSO WORKS WHEN THE TABLE IS REMOTE) */
				BILL.DEPOSIT_NUMBER
				, BILL.DI_DEBTOR
				, BILL.DI_AMOUNT
				, R.CUSTOMER_ID
				, R.CUSTOMER_NUMBER
				, BILL.TRANSACTION_DATE
				, BILL.TRX_ABOUT_CODE
				, BILL.TRX_ABOUT_NAME
				, BILL.CUSTOMER_ID_OPPOSITE AS PEER_CUSTOMER_ID     /* COUNTERPARTY''S CUSTOMER ID, NULL OUTSIDE OUR BANK */
				, CASE WHEN DI_DEBTOR = 1 THEN BILL.DEST_DEPOSIT_NUMBER WHEN DI_DEBTOR = 0 THEN SRC_DEPOSIT_NUMBER END AS TRX_DEPOSIT_NUMBER
				, BILL.TRX_FIRST_NAME ||''''|| BILL.TRX_LAST_NAME AS TRX_NAME
			FROM
				UDL.AML_BILL_TRANSACTION_ARCH BILL INNER JOIN EXPAND_DEPOSIT R ON R.DEPOSIT_NUMBER = BILL.DEPOSIT_NUMBER
			WHERE
				1=1
				AND ' || V_START_DATE || '  ' || V_END_DATE || '
				AND BILL.TRANSACTION_TYPE_CODE <> 1010
		)
		, BASE_TRX2 AS
		(
			SELECT /*+MATERIALIZE*/
				CUSTOMER_ID
				, CUSTOMER_NUMBER
				, DEPOSIT_NUMBER
				, TRX_DEPOSIT_NUMBER
				, DI_DEBTOR
				, PEER_CUSTOMER_ID
				, MAX(TRANSACTION_DATE) AS TRANSACTION_DATE
				, MIN(TRX_ABOUT_CODE) AS TRX_ABOUT_CODE
				, MIN(TRX_ABOUT_NAME) AS TRX_ABOUT_NAME
				, CASE WHEN DI_DEBTOR = 1 THEN DEPOSIT_NUMBER ELSE TRX_DEPOSIT_NUMBER END AS SRC_DEPOSIT_NUMBER
				, CASE WHEN DI_DEBTOR = 0 THEN DEPOSIT_NUMBER ELSE TRX_DEPOSIT_NUMBER END AS DEST_DEPOSIT_NUMBER
				, TRX_NAME
				, SUM(DI_AMOUNT) AS TOTAL_AMOUNT
				, COUNT(*) AS CNT
				, MAX(DI_AMOUNT) AS MAX_AMOUNT
			FROM
				BILL_TRX2
			GROUP BY
				CUSTOMER_ID
				, CUSTOMER_NUMBER
				, DEPOSIT_NUMBER
				, TRX_DEPOSIT_NUMBER
				, DI_DEBTOR
				, TRX_NAME     /* KEEPS OUTSIDE-BANK PEOPLE WITHOUT AN ACCOUNT NUMBER APART */
				, PEER_CUSTOMER_ID
		)
		, TRX2 AS
		(
			SELECT
				T1.TRANSACTION_DATE
				, T1.CUSTOMER_ID
				, T1.CUSTOMER_NUMBER
				, T1.DI_DEBTOR
				, NVL(T1.SRC_DEPOSIT_NUMBER ,0) AS SRC_DEPOSIT_NUMBER
				, NVL(T1.DEST_DEPOSIT_NUMBER ,0) AS DEST_DEPOSIT_NUMBER
				, T1.PEER_CUSTOMER_ID
				, NVL(T1.PEER_CUSTOMER_ID, 9000000000000 + ORA_HASH(NVL(T1.TRX_DEPOSIT_NUMBER, NVL(T1.TRX_NAME, ''UNKNOWN'')))) AS PEER_KEY     /* OUR CUSTOMER : CUSTOMER ID; OUTSIDE OUR BANK : ONE KEY PER ACCOUNT */
				, T1.TRX_NAME AS PEER_NAME
				, T1.TRX_ABOUT_CODE
				, T1.TRX_ABOUT_NAME
				, T1.TOTAL_AMOUNT
				, T1.CNT
				, T1.MAX_AMOUNT
				, SUM(T1.TOTAL_AMOUNT) OVER (PARTITION BY T1.CUSTOMER_ID, NVL(T1.PEER_CUSTOMER_ID, 9000000000000 + ORA_HASH(NVL(T1.TRX_DEPOSIT_NUMBER, NVL(T1.TRX_NAME, ''UNKNOWN''))))) AS PEER_TOTAL
			FROM
				BASE_TRX2 T1
			WHERE
				NVL(T1.PEER_CUSTOMER_ID,0) NOT IN (SELECT CUSTOMER_ID FROM ROOT_CUSTOMER)     /* THE ROOT IS ALREADY CONNECTED, DO NOT RANK IT AGAIN */
		)
		, PEER_RANK2 AS
		(
			SELECT /*+MATERIALIZE*/
				T.*
				, DENSE_RANK() OVER (PARTITION BY T.CUSTOMER_ID ORDER BY T.PEER_TOTAL DESC, T.PEER_KEY) AS RN
				, 2 AS HOP
			FROM
				TRX2 T
		)
		/* ===== HOP 3 : THE TOP 3 OF EACH HOP-2 PERSON WHO ARE INDIVIDUALS (IS_REAL = 1) ARE EXPANDED ===== */
		, EXPAND_CUSTOMER3 AS
		(
			SELECT /*+ USE_NL(C) */
				C.ID AS PEER_CUSTOMER_ID
				, C.CUSTOMER_NUMBER AS PEER_NUMBER
			FROM
				(
					SELECT /*+ NO_MERGE */ DISTINCT
						P.PEER_CUSTOMER_ID
					FROM
						PEER_RANK2 P
					WHERE
						P.RN <= 3
						AND P.PEER_CUSTOMER_ID NOT IN (SELECT CUSTOMER_ID FROM ROOT_CUSTOMER)            /* THE ROOT IS NEVER EXPANDED AGAIN */
						AND P.PEER_CUSTOMER_ID NOT IN (SELECT PEER_CUSTOMER_ID FROM EXPAND_CUSTOMER)     /* ALREADY EXPANDED AT HOP 2 */
				) P INNER JOIN UDL.CSTM_CUSTOMER@drep C ON P.PEER_CUSTOMER_ID = C.ID     /* AT MOST 18 LOOKUPS */
			WHERE
				C.IS_REAL = 1
		)
		, EXPAND_DEPOSIT3 AS
		(
			SELECT /*+ LEADING(E) USE_NL(D) */
				D.CUSTOMER_ID
				, D.CUSTOMER_NUMBER
				, D.DEPOSIT_NUMBER
			FROM
				EXPAND_CUSTOMER3 E INNER JOIN UDL.DPST_DEPOSIT_CUSTOMER D ON D.CUSTOMER_NUMBER = E.PEER_NUMBER
		)
		, BILL_TRX3 AS
		(
			SELECT /*+ LEADING(R) USE_NL(BILL) */     /* ONE KEYED LOOKUP PER DEPOSIT (ALSO WORKS WHEN THE TABLE IS REMOTE) */
				BILL.DEPOSIT_NUMBER
				, BILL.DI_DEBTOR
				, BILL.DI_AMOUNT
				, R.CUSTOMER_ID
				, R.CUSTOMER_NUMBER
				, BILL.TRANSACTION_DATE
				, BILL.TRX_ABOUT_CODE
				, BILL.TRX_ABOUT_NAME
				, BILL.CUSTOMER_ID_OPPOSITE AS PEER_CUSTOMER_ID     /* COUNTERPARTY''S CUSTOMER ID, NULL OUTSIDE OUR BANK */
				, CASE WHEN DI_DEBTOR = 1 THEN BILL.DEST_DEPOSIT_NUMBER WHEN DI_DEBTOR = 0 THEN SRC_DEPOSIT_NUMBER END AS TRX_DEPOSIT_NUMBER
				, BILL.TRX_FIRST_NAME ||''''|| BILL.TRX_LAST_NAME AS TRX_NAME
			FROM
				UDL.AML_BILL_TRANSACTION_ARCH BILL INNER JOIN EXPAND_DEPOSIT3 R ON R.DEPOSIT_NUMBER = BILL.DEPOSIT_NUMBER
			WHERE
				1=1
				AND ' || V_START_DATE || '  ' || V_END_DATE || '
				AND BILL.TRANSACTION_TYPE_CODE <> 1010
		)
		, BASE_TRX3 AS
		(
			SELECT /*+MATERIALIZE*/
				CUSTOMER_ID
				, CUSTOMER_NUMBER
				, DEPOSIT_NUMBER
				, TRX_DEPOSIT_NUMBER
				, DI_DEBTOR
				, PEER_CUSTOMER_ID
				, MAX(TRANSACTION_DATE) AS TRANSACTION_DATE
				, MIN(TRX_ABOUT_CODE) AS TRX_ABOUT_CODE
				, MIN(TRX_ABOUT_NAME) AS TRX_ABOUT_NAME
				, CASE WHEN DI_DEBTOR = 1 THEN DEPOSIT_NUMBER ELSE TRX_DEPOSIT_NUMBER END AS SRC_DEPOSIT_NUMBER
				, CASE WHEN DI_DEBTOR = 0 THEN DEPOSIT_NUMBER ELSE TRX_DEPOSIT_NUMBER END AS DEST_DEPOSIT_NUMBER
				, TRX_NAME
				, SUM(DI_AMOUNT) AS TOTAL_AMOUNT
				, COUNT(*) AS CNT
				, MAX(DI_AMOUNT) AS MAX_AMOUNT
			FROM
				BILL_TRX3
			GROUP BY
				CUSTOMER_ID
				, CUSTOMER_NUMBER
				, DEPOSIT_NUMBER
				, TRX_DEPOSIT_NUMBER
				, DI_DEBTOR
				, TRX_NAME     /* KEEPS OUTSIDE-BANK PEOPLE WITHOUT AN ACCOUNT NUMBER APART */
				, PEER_CUSTOMER_ID
		)
		, TRX3 AS
		(
			SELECT
				T1.TRANSACTION_DATE
				, T1.CUSTOMER_ID
				, T1.CUSTOMER_NUMBER
				, T1.DI_DEBTOR
				, NVL(T1.SRC_DEPOSIT_NUMBER ,0) AS SRC_DEPOSIT_NUMBER
				, NVL(T1.DEST_DEPOSIT_NUMBER ,0) AS DEST_DEPOSIT_NUMBER
				, T1.PEER_CUSTOMER_ID
				, NVL(T1.PEER_CUSTOMER_ID, 9000000000000 + ORA_HASH(NVL(T1.TRX_DEPOSIT_NUMBER, NVL(T1.TRX_NAME, ''UNKNOWN'')))) AS PEER_KEY     /* OUR CUSTOMER : CUSTOMER ID; OUTSIDE OUR BANK : ONE KEY PER ACCOUNT */
				, T1.TRX_NAME AS PEER_NAME
				, T1.TRX_ABOUT_CODE
				, T1.TRX_ABOUT_NAME
				, T1.TOTAL_AMOUNT
				, T1.CNT
				, T1.MAX_AMOUNT
				, SUM(T1.TOTAL_AMOUNT) OVER (PARTITION BY T1.CUSTOMER_ID, NVL(T1.PEER_CUSTOMER_ID, 9000000000000 + ORA_HASH(NVL(T1.TRX_DEPOSIT_NUMBER, NVL(T1.TRX_NAME, ''UNKNOWN''))))) AS PEER_TOTAL
			FROM
				BASE_TRX3 T1
			WHERE
				NVL(T1.PEER_CUSTOMER_ID,0) NOT IN (SELECT CUSTOMER_ID FROM ROOT_CUSTOMER
				                                   UNION ALL
				                                   SELECT PEER_CUSTOMER_ID FROM EXPAND_CUSTOMER)   /* ROOT AND HOP-2 PEOPLE ARE ALREADY CONNECTED */
		)
		, PEER_RANK3 AS
		(
			SELECT
				T.*
				, DENSE_RANK() OVER (PARTITION BY T.CUSTOMER_ID ORDER BY T.PEER_TOTAL DESC, T.PEER_KEY) AS RN
				, 3 AS HOP
			FROM
				TRX3 T
		)
		/* ===== BOTH HOPS TOGETHER ===== */
		, ALL_RANK AS
		(
			SELECT /*+MATERIALIZE*/
				*
			FROM
			(
				SELECT * FROM PEER_RANK
				UNION ALL
				SELECT * FROM PEER_RANK2
				UNION ALL
				SELECT * FROM PEER_RANK3
			)
		)
		, SLICE AS
		(
			/* TOP 3 OF EACH CENTER : THE ROOT''S ARE SHOWN AT START, AN EXPANDED PERSON''S (HOP 2 OR 3) ARE SHOWN WHEN THAT PERSON IS CLICKED */
			SELECT
				T.TRANSACTION_DATE
				, T.CUSTOMER_ID
				, T.CUSTOMER_NUMBER
				, T.DI_DEBTOR
				, T.SRC_DEPOSIT_NUMBER
				, T.DEST_DEPOSIT_NUMBER
				, T.PEER_KEY
				, T.PEER_CUSTOMER_ID
				, T.PEER_NAME
				, T.TRX_ABOUT_CODE
				, T.TRX_ABOUT_NAME
				, T.TOTAL_AMOUNT
				, T.CNT
				, T.MAX_AMOUNT
				, CASE WHEN T.HOP >= 2 THEN T.CUSTOMER_NUMBER END AS PARENT_NODE_ID
				, T.HOP
			FROM
				ALL_RANK T
			WHERE
				T.RN <= 3
			UNION ALL
			/* EVERYONE ELSE OF EACH CENTER, FOLDED INTO THAT CENTER''S OTHER : -(CENTER * 10 + 1) */
			SELECT
				T.TRANSACTION_DATE
				, T.CUSTOMER_ID
				, T.CUSTOMER_NUMBER
				, T.DI_DEBTOR
				, T.SRC_DEPOSIT_NUMBER
				, T.DEST_DEPOSIT_NUMBER
				, -(T.CUSTOMER_NUMBER * 10 + 1)
				, NULL
				, ''Other''
				, NULL
				, NULL
				, T.TOTAL_AMOUNT
				, T.CNT
				, T.MAX_AMOUNT
				, CASE WHEN T.HOP >= 2 THEN T.CUSTOMER_NUMBER END
				, T.HOP
			FROM
				ALL_RANK T
			WHERE
				T.RN > 3
			UNION ALL
			/* ROOT ONLY : RANKS 4..6, SHOWN WHEN THE ROOT''S OTHER IS CLICKED */
			SELECT
				T.TRANSACTION_DATE
				, T.CUSTOMER_ID
				, T.CUSTOMER_NUMBER
				, T.DI_DEBTOR
				, T.SRC_DEPOSIT_NUMBER
				, T.DEST_DEPOSIT_NUMBER
				, T.PEER_KEY
				, T.PEER_CUSTOMER_ID
				, T.PEER_NAME
				, T.TRX_ABOUT_CODE
				, T.TRX_ABOUT_NAME
				, T.TOTAL_AMOUNT
				, T.CNT
				, T.MAX_AMOUNT
				, -(T.CUSTOMER_NUMBER * 10 + 1)
				, T.HOP
			FROM
				ALL_RANK T
			WHERE
				T.HOP = 1
				AND T.RN BETWEEN 4 AND 6
			UNION ALL
			/* ROOT ONLY : RANKS 7+, A FINAL OTHER -(ROOT * 10 + 2), SHOWN WHEN THE ROOT''S OTHER IS CLICKED */
			SELECT
				T.TRANSACTION_DATE
				, T.CUSTOMER_ID
				, T.CUSTOMER_NUMBER
				, T.DI_DEBTOR
				, T.SRC_DEPOSIT_NUMBER
				, T.DEST_DEPOSIT_NUMBER
				, -(T.CUSTOMER_NUMBER * 10 + 2)
				, NULL
				, ''Other''
				, NULL
				, NULL
				, T.TOTAL_AMOUNT
				, T.CNT
				, T.MAX_AMOUNT
				, -(T.CUSTOMER_NUMBER * 10 + 1)
				, T.HOP
			FROM
				ALL_RANK T
			WHERE
				T.HOP = 1
				AND T.RN > 6
		)
		, EDGES AS
		(
			SELECT
				MAX(T.TRANSACTION_DATE) AS TRANSACTION_DATE
				, CASE WHEN MIN(T.SRC_DEPOSIT_NUMBER) = MAX(T.SRC_DEPOSIT_NUMBER) THEN MIN(T.SRC_DEPOSIT_NUMBER) END AS SRC_DEPOSIT_NUMBER
				, CASE WHEN MIN(T.DEST_DEPOSIT_NUMBER) = MAX(T.DEST_DEPOSIT_NUMBER) THEN MIN(T.DEST_DEPOSIT_NUMBER) END AS DEST_DEPOSIT_NUMBER
				, T.CUSTOMER_ID
				, T.CUSTOMER_NUMBER
				, T.DI_DEBTOR
				, T.PEER_KEY
				, T.PARENT_NODE_ID
				, T.HOP
				, MIN(T.PEER_CUSTOMER_ID) AS PEER_CUSTOMER_ID
				, MIN(T.PEER_NAME) AS PEER_NAME
				, MIN(T.TRX_ABOUT_CODE) AS TRX_ABOUT_CODE
				, MIN(T.TRX_ABOUT_NAME) AS TRX_ABOUT_NAME
				, SUM(T.TOTAL_AMOUNT) AS TOTAL_AMOUNT
				, SUM(T.CNT) AS CNT
				, MAX(T.MAX_AMOUNT) AS MAX_AMOUNT
			FROM
				SLICE T
			GROUP BY
				T.CUSTOMER_ID
				, T.CUSTOMER_NUMBER
				, T.DI_DEBTOR
				, T.PEER_KEY
				, T.PARENT_NODE_ID
				, T.HOP
		)
		, NODE_EDGES AS
		(
			SELECT /*+MATERIALIZE*/
				TRANSACTION_DATE
				, CUSTOMER_ID
				, PEER_KEY
				, PEER_CUSTOMER_ID
				, PEER_NAME
				, PARENT_NODE_ID
			FROM
				EDGES
		)
		, ALLNODES AS
		(
			SELECT
				TRANSACTION_DATE
				, PEER_CUSTOMER_ID AS NODE_CUSTOMER_ID                                   /* OUR CUSTOMER */
				, CASE WHEN PEER_CUSTOMER_ID IS NULL THEN PEER_KEY END AS NODE_KEY        /* OTHER NODE OR OUTSIDE-BANK ACCOUNT */
				, PEER_NAME AS NODE_NAME
			FROM
				NODE_EDGES
			UNION ALL
			SELECT
				TRANSACTION_DATE
				, CUSTOMER_ID                                                             /* THE CENTER (ROOT OR EXPANDED PERSON) IS ALWAYS OUR CUSTOMER */
				, NULL
				, NULL
			FROM
				NODE_EDGES
		)
		, NODE_LIST AS
		(
			SELECT
				NODE_CUSTOMER_ID
				, NODE_KEY
				, MAX(TRANSACTION_DATE) AS TRANSACTION_DATE
				, MIN(NODE_NAME) AS NODE_NAME
			FROM
				ALLNODES
			GROUP BY
				NODE_CUSTOMER_ID
				, NODE_KEY
		)
		, PARENTS AS
		(
			SELECT DISTINCT
				PARENT_NODE_ID AS NODE_ID
			FROM
				NODE_EDGES
			WHERE
				PARENT_NODE_ID IS NOT NULL
		)
		, NODE_INFO AS
		(
			SELECT /*+ MATERIALIZE USE_NL(C) */
				N.TRANSACTION_DATE
				, NVL(C.CUSTOMER_NUMBER, NVL(N.NODE_KEY, N.NODE_CUSTOMER_ID)) AS NODE_ID
				, C.CUSTOMER_NUMBER
				, C.IS_REAL
				, C.REAL_OR_LEGAL
				, C.FIRST_NAME
				, C.LAST_NAME
				, NVL(C.CUSTOMER_NAME, N.NODE_NAME) AS CUSTOMER_NAME     /* OTHER NODES AND OUTSIDE-BANK ACCOUNTS TAKE THEIR NAME FROM THE EDGES */
				, C.NATIONAL_CODE
			FROM
				NODE_LIST N LEFT JOIN UDL.CSTM_CUSTOMER@drep C ON N.NODE_CUSTOMER_ID = C.ID     /* ONE LOOKUP PER NODE */
		)
		/* ===== LOCATION : THE NODE''S ACTIVE ACCOUNTS (STATUS_ID = 18, IS_REAL = 1) AND THEIR BRANCH; HIGH-RISK LIST OF 1400/10/28 ===== */
		, NODE_DEPOSIT_BRANCH AS
		(
			SELECT /*+ LEADING(I D B) USE_NL(D B) */
				I.CUSTOMER_NUMBER
				, B.BRANCH_CODE
				, B.BRANCH_NAME
				, CASE WHEN B.BRANCH_CODE IN (2101, 3502, 1101, 2001, 2003, 398, 3901, 3902, 3903, 3904, 3906, 3907, 3908, 3909, 3910, 3911, 3912, 2501) THEN 1 ELSE 0 END AS IS_HIGH_RISK
			FROM
				NODE_INFO I
				INNER JOIN UDL.DPST_DEPOSIT_CUSTOMER D ON D.CUSTOMER_NUMBER = I.CUSTOMER_NUMBER     /* THE NODE''S ACCOUNTS, BY CUSTOMER NUMBER */
				INNER JOIN UDL.DPST_DEPOSIT@drep B ON B.DEPOSIT_NUMBER = D.DEPOSIT_NUMBER                /* ONE KEYED LOOKUP PER ACCOUNT */
			WHERE
				I.IS_REAL = 1                                       /* LEGAL CUSTOMERS (MANY ACCOUNTS) ARE SKIPPED BEFORE THE LOOKUP */
				AND B.STATUS_ID = 18                                /* ACTIVE ACCOUNTS */
				AND B.IS_REAL = 1
				AND B.MAIN_CUSTOMER_NUMBER = I.CUSTOMER_NUMBER      /* THE NODE IS THE MAIN CUSTOMER OF THE ACCOUNT */
		)
		, NODE_BRANCH AS
		(
			SELECT
				CUSTOMER_NUMBER
				, BRANCH_CODE
				, BRANCH_NAME
				, IS_HIGH_RISK
			FROM
			(
				SELECT
					T.*
					, ROW_NUMBER() OVER (PARTITION BY T.CUSTOMER_NUMBER ORDER BY T.IS_HIGH_RISK DESC, T.BRANCH_CODE) AS RN     /* A HIGH-RISK BRANCH FIRST, IF THERE IS ONE */
				FROM
					NODE_DEPOSIT_BRANCH T
			)
			WHERE
				RN = 1     /* ONE BRANCH PER NODE */
		)
		SELECT
			I.TRANSACTION_DATE
			, I.NODE_ID
			, I.IS_REAL
			, I.REAL_OR_LEGAL
			, I.FIRST_NAME
			, I.LAST_NAME
			, I.CUSTOMER_NAME
			, I.NATIONAL_CODE
			, CASE WHEN P.NODE_ID IS NULL THEN 0 ELSE 1 END AS IS_EXPANDABLE
			, B.BRANCH_CODE
			, B.BRANCH_NAME
			, CASE B.IS_HIGH_RISK WHEN 1 THEN ''مناطق پرخطر'' WHEN 0 THEN ''مناطق نرمال'' END AS LOCATION_STATUS     /* NULL : OTHER NODE / OUTSIDE OUR BANK */
		FROM
			NODE_INFO I
				LEFT JOIN NODE_BRANCH B ON B.CUSTOMER_NUMBER = I.CUSTOMER_NUMBER
				LEFT JOIN PARENTS P ON P.NODE_ID = I.NODE_ID
      )
    '
